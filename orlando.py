
numeros = [0,1,3, 4, 5]
for numero in numeros:
    print(numero)

# Este es un ejemplo de un bucle for en Python que recorre una lista de
#  números y los imprime uno por uno. La lista `numeros` contiene los elementos 
# 0, 1, 3, 4 y 5. Al ejecutar este código, se imprimirá cada número en una 
# nueva línea.

frutas = ["manzana", "banana", "cereza"]
for fruta in frutas:
    print(fruta)